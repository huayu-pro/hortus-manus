export const copy = { zh, en } as const

export type Copy = DeepCopy<typeof zh>
export type CopyLang = Lang

export const COPY_LANGS: readonly Lang[] = ['zh', 'en']

export function isLang(value: unknown): value is Lang {
  return value === 'zh' || value === 'en'
}

/** Returns the full copy deck for a language. */
export function getCopy(lang: Lang): Copy {
  return (lang === 'en' ? en : zh) as Copy
}

/** Pair helper: primary language copy plus its counterpart for editorial pairing. */
export function getBilingual(lang: Lang): { primary: Copy; secondary: Copy } {
  return { primary: getCopy(lang), secondary: getCopy(lang === 'zh' ? 'en' : 'zh') }
}
